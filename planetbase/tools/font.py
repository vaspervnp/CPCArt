SETS = {4: G4, 6: G6}


def glyph_w(w=None):
    """Στήλες μελανιού — η τελευταία στήλη του κελιού είναι το διάστιχο."""
    return (w or WIDTH) - 1


def columns(w=None):
    """Πόσες στήλες κειμένου χωράνε στα 160 pixel."""
    return SCREEN_W // (w or WIDTH)


def glyph_size(w=None):
    """Bytes ανά γλύφο."""
    return (w or WIDTH) // 2 * FONT_H


def total_size(w=None):
    return glyph_size(w) * GLYPH_COUNT


def glyph_rows(ch, w=None):
    """Επιστρέφει 8 γραμμές x w χαρακτήρες για τον χαρακτήρα ch."""
    w = w or WIDTH
    if w not in SETS:
        raise ValueError("άγνωστο πλάτος κελιού %r — επιτρέπονται %s"
                         % (w, sorted(SETS)))
    art = SETS[w][ch].split("/")
    if len(art) != 7:
        raise ValueError("ο γλύφος %r (%dpx) έχει %d γραμμές, περίμενα 7"
                         % (ch, w, len(art)))
    gw = glyph_w(w)
    rows = []
    for r in art:
        if len(r) == gw:
            r += BG                      # η τελευταία στήλη είναι το διάστιχο
        elif len(r) != w:
            raise ValueError("ο γλύφος %r (%dpx) έχει γραμμή %r πλάτους %d — "
                             "επιτρέπονται %d ή %d" % (ch, w, r, len(r), gw, w))
        for c in r:
            if c not in (INK, BG):
                raise ValueError("ο γλύφος %r έχει άγνωστο χαρακτήρα %r"
                                 % (ch, c))
        rows.append(r)
    rows.append(BG * w)                  # γραμμή 7 — διάστιχο σειρών
    return rows


def glyph_pens(ch, w=None):
    """Πίνακας [8][w] από pens για τον χαρακτήρα ch."""
    return [[PEN_INK if c == INK else PEN_BG for c in row]
            for row in glyph_rows(ch, w)]


def charset():
    """Οι 96 χαρακτήρες με τη σειρά αποθήκευσης (ASCII 32..127)."""
    return [chr(FIRST_CHAR + i) for i in range(GLYPH_COUNT)]
