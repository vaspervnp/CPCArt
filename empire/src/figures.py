"""Η ανθρώπινη φιγούρα σε 8x16 pixels Mode 0, κατά στρώσεις.

ΓΙΑΤΙ ΤΟΣΟ ΣΤΕΝΗ

Το pixel του Mode 0 είναι **διπλάσια φαρδύ από ψηλό**. Μια φιγούρα 16 γραμμών
ψηλή είναι 16 μονάδες οθόνης· για ανθρώπινη αναλογία (ύψος περίπου διπλάσιο
από τους ώμους) οι ώμοι θέλουν 8 μονάδες, δηλαδή **4 pixels**, και το κεφάλι
4 μονάδες, δηλαδή **2 pixels**.

Δεν χωράει πρόσωπο, και δεν χρειάζεται: σε αυτό το μέγεθος οι μονάδες
ξεχωρίζουν από τη ΣΙΛΟΥΕΤΑ (κράνος, όπλο, ασπίδα) και από το ΧΡΩΜΑ.

Δεν χωράει ούτε περίγραμμα γύρω από το κεφάλι: το `..KssK..` το κάνει 4 pixels
φαρδύ, δηλαδή 8 μονάδες επί 3 ψηλές — πλακουτσωτό. Το περίγραμμα μπαίνει μόνο
όπου περισσεύει πλάτος (πόδια, πέλματα) και αλλιώς τη δουλειά την κάνει η
σκιά κάτω από τα πόδια.

ΟΙ ΓΡΑΜΜΕΣ

     0      ελεύθερη — λοφίο, αιχμή δόρατος, τόξο
     1      μαλλιά ή κράνος
     2-4    κεφάλι
     5-9    ώμοι, κορμός, ζώνη
    10-14   πόδια, πέλματα στη 14
    15      σκιά στο έδαφος

Το ΜΠΟΜΠ του βαδίσματος ανεβάζει ΜΟΝΟ τον κορμό και το κεφάλι. Στην πρώτη
δοκιμή ανέβαζε ολόκληρη τη φιγούρα και τα πέλματα ξεκολλούσαν από το έδαφος:
η μονάδα φαινόταν να αιωρείται αντί να περπατάει.

ΟΙ ΟΨΕΙΣ

Τρεις ζωγραφίζονται — S (προς τον παίκτη), E (δεξιά), N (πλάτη). Η W είναι
καθρέφτισμα της E και δεν ζωγραφίζεται ποτέ.
"""
from gfx import blank, parse_art, shift, stamp

W, H = 8, 16

Y_HAIR = 1
Y_HEAD = 2        # γραμμές 2-4
Y_BODY = 5        # γραμμές 5-9
Y_LEGS = 10       # γραμμές 10-14, πέλματα στη 14
Y_GROUND = 15

FACINGS = ('s', 'e', 'n')          # η 'w' βγαίνει από την 'e' με καθρέφτισμα


# --------------------------------------------------------------- κεφάλι
# 2 pixels φαρδύ στο x=3,4 — 4 μονάδες οθόνης επί 3 γραμμές, σχεδόν τετράγωνο.
HEAD = {
    's': """
         ...ss...
         ...ss...
         ...ss...
         """,
    'e': """
         ...ss...
         ...sS...
         ...ss...
         """,
    'n': """
         ...dd...
         ...dd...
         ...ds...
         """,
}

HAIR = {'s': '...dd...', 'e': '...dd...', 'n': '..dddd..'}


# --------------------------------------------------------------- κορμός
# 4 pixels στο x=2..5. Τα χέρια είναι το ένα pixel δίπλα, x=1 και x=6.
# Στην όψη E το πίσω χέρι κρύβεται.
BODY = {
    's': """
         ..TTTT..
         .sTTTTs.
         .sTTTTs.
         ..TTTT..
         ..KttK..
         """,
    'e': """
         ..TTTT..
         ..TTTTs.
         ..TTTTs.
         ..TTTT..
         ..KttK..
         """,
    'n': """
         ..TTTT..
         .sTTTTs.
         .sTTTTs.
         ..TTTT..
         ..KttK..
         """,
}


# ---------------------------------------------------------------- πόδια
# Πέντε γραμμές, πέλματα ΠΑΝΤΑ στην τελευταία: ό,τι κι αν κάνει ο κορμός, τα
# πόδια πατάνε. Δύο στάσεις — ανοιχτά και κλειστά — εναλλάξ.
#
# Σε 8 pixels πλάτος και 1 pixel ανά πόδι δεν χωράει τετράφασο βάδισμα με
# τέσσερις ΔΙΑΦΟΡΕΤΙΚΕΣ στάσεις: οι δύο ενδιάμεσες θα διέφεραν κατά μισό
# pixel, που δεν υπάρχει. Ο κύκλος είναι ανοιχτά / κλειστά+μπομπ / ανοιχτά /
# κλειστά+μπομπ, και στην όψη E οι δύο «ανοιχτές» έχουν ΑΛΛΟ πόδι μπροστά —
# εκεί φαίνεται, στις άλλες όψεις όχι.
APART = """
        ..d..d..
        ..d..d..
        ..d..d..
        ..K..K..
        .KK..KK.
        """
TOGETHER = """
        ...dd...
        ...dd...
        ...dd...
        ...KK...
        ..KKKK..
        """
# Στην όψη E η δρασκελιά είναι ΜΠΡΟΣΤΑ-ΠΙΣΩ, όχι δεξιά-αριστερά: το μπροστινό
# πόδι πάει προς τα δεξιά (εκεί κοιτάει) και το πίσω μένει αριστερά. Η πρώτη
# δοκιμή άνοιγε και τα δύο συμμετρικά και έβγαινε στάση καβάλα, όχι βάδισμα.
STRIDE_R = """
        ...dd...
        ...d.d..
        ..d...d.
        ..K...K.
        .KK...KK
        """
STRIDE_L = """
        ...dd...
        ..d.d...
        .d...d..
        .K...K..
        KK...KK.
        """

LEGS = {
    's': (APART, TOGETHER, APART, TOGETHER),
    'e': (STRIDE_R, TOGETHER, STRIDE_L, TOGETHER),
    'n': (APART, TOGETHER, APART, TOGETHER),
}

BOB = (0, -1, 0, -1)        # πόσο ανεβαίνει Ο ΚΟΡΜΟΣ ανά φάση

# Η σκιά στο έδαφος. Δεν είναι διακόσμηση: σε χάρτη με γρασίδι μια φιγούρα 4
# pixels χωρίς περίγραμμα χάνεται, και η σκιά τη γειώνει με ένα μόνο pixel
# ύψος — φθηνότερα από περίγραμμα, που θα έτρωγε δύο pixels από το πλάτος.
# Είναι ΠΙΟ ΦΑΡΔΙΑ από τα πέλματα ώστε να διαβάζεται ως σκιά και να μη λιώνει
# με τα σκούρα περιγράμματα των ποδιών.
SHADOW = '.KKKKKK.'


def upper(facing, hair=True):
    """Κεφάλι, μαλλιά και κορμός, στις δικές τους γραμμές."""
    img = blank(W, H, None)
    stamp(img, parse_art(BODY[facing]), 0, Y_BODY)
    stamp(img, parse_art(HEAD[facing]), 0, Y_HEAD)
    if hair:
        stamp(img, parse_art(HAIR[facing]), 0, Y_HAIR)
    return img


def lower(facing, phase=0):
    img = blank(W, H, None)
    stamp(img, parse_art(LEGS[facing][phase]), 0, Y_LEGS)
    return img


def walking(facing, phase=0, hair=True, shadow=True):
    """Ολόκληρη η φιγούρα, με το μπομπ μόνο στον κορμό."""
    img = lower(facing, phase)
    up = upper(facing, hair)
    if BOB[phase]:
        up = shift(up, 0, BOB[phase])
    stamp(img, up)
    if shadow:
        stamp(img, parse_art(SHADOW), 0, Y_GROUND)
    return img
