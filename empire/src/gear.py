def art(table, key, phase=0):
    """-> γραμμές pens, ή None αν η μονάδα δεν έχει αυτό το κομμάτι."""
    if key is None:
        return None
    v = table[key]
    if isinstance(v, tuple):
        v = v[phase]
    return parse_art(v)
